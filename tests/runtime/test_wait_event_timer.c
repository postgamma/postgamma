#include "postgamma/virtual_signal.h"
#include "../check.h"
#include <limits.h>

typedef uint32_t uint32;
typedef int64_t instr_time;
typedef struct Latch
{
	bool is_set;
	bool maybe_sleeping;
} Latch;
typedef struct WaitEvent
{
	int fd;
	int pos;
	void *user_data;
	uint32 events;
} WaitEvent;
typedef struct WaitEventSet
{
	Latch *latch;
	int latch_pos;
	WaitEvent *events;
} WaitEventSet;

#define PGINVALID_SOCKET (-1)
#define WL_LATCH_SET 1
#define WL_SOCKET_READABLE 2
#define Assert CHECK
#define INSTR_TIME_SET_CURRENT(value) ((value) = Now)
#define INSTR_TIME_SET_ZERO(value) ((value) = 0)
#define INSTR_TIME_SUBTRACT(value, start) ((value) -= (start))
#define INSTR_TIME_GET_MILLISEC(value) ((value) / 1000)
#define pg_memory_barrier() ((void) 0)
#define pgstat_report_wait_start(info) ((void) (info))
#define pgstat_report_wait_end() ((void) 0)

static PostgammaVirtualTimer Timer;
static int64_t Now;
static int WaitCalls;
static bool Rearm;
static bool waiting;
static bool TimeoutOnly;
static long RequestedTimeout;

static long
postgamma_backend_adjust_wait_timeout(long requested)
{
	return postgamma_virtual_timer_adjust_wait(&Timer, requested, Now);
}

static bool
postgamma_backend_timeout_wait_expired(int result)
{
	return postgamma_virtual_timer_wait_expired(&Timer, result);
}

static int
postgamma_backend_filter_wake_events(WaitEvent *events, int count)
{
	(void) events;
	return count;
}

static void
postgamma_dispatch_pending_signals(void)
{
	if (postgamma_virtual_timer_due(&Timer, Now))
	{
		struct itimerval value = {0};

		/* Match callbacks that rearm or disarm their timeout. */
		value.it_value.tv_usec = Rearm ? 1000 : 0;
		CHECK(postgamma_virtual_timer_set(&Timer, ITIMER_REAL, &value, NULL, Now) == 0);
	}
}

static int
WaitEventSetWaitBlock(WaitEventSet *set, int timeout, WaitEvent *events, int count)
{
	(void) set;
	CHECK(count == 1);
	CHECK(++WaitCalls <= (TimeoutOnly && Rearm ? 5 : 2));
	if (WaitCalls == 1)
	{
		CHECK(timeout == 1);
		Now += 1000;
		return -1;
	}
	if (TimeoutOnly)
	{
		CHECK(timeout == (Rearm ? 1 : RequestedTimeout - 1));
		Now += timeout * 1000;
		return -1;
	}
	events->events = WL_SOCKET_READABLE;
	return 1;
}

/* Generated by the test from the real upstream function and project adapter. */
#include "wait_event_loop.inc"

int
main(void)
{
	for (int rearm = 0; rearm < 2; rearm++)
	{
		Latch latch = {0};
		WaitEvent event = {.events = UINT32_MAX};
		WaitEventSet set = {.latch = &latch, .events = &event};
		struct itimerval value = {.it_value = {.tv_usec = 1000}};

		Rearm = rearm;
		Now = 0;
		WaitCalls = 0;
		CHECK(postgamma_virtual_timer_set(&Timer, ITIMER_REAL, &value, NULL, Now) == 0);
		CHECK(WaitEventSetWait(&set, -1, &event, 1, 0) == 1);
		CHECK(event.events == WL_SOCKET_READABLE && WaitCalls == 2);
		CHECK(!latch.maybe_sleeping && !waiting);
	}
	/* Repeated timer wakeups must not extend a finite caller deadline. */
	for (int rearm = 0; rearm < 2; rearm++)
	{
		Latch latch = {0};
		WaitEvent event = {.events = UINT32_MAX};
		WaitEventSet set = {.latch = &latch, .events = &event};
		struct itimerval value = {.it_value = {.tv_usec = 1000}};

		Rearm = rearm;
		TimeoutOnly = true;
		RequestedTimeout = 5;
		Now = 0;
		WaitCalls = 0;
		CHECK(postgamma_virtual_timer_set(&Timer, ITIMER_REAL, &value, NULL, Now) == 0);
		CHECK(WaitEventSetWait(&set, RequestedTimeout, &event, 1, 0) == 0);
		CHECK(Now == RequestedTimeout * 1000);
		CHECK(!latch.maybe_sleeping && !waiting);
	}
	return 0;
}
